#!/usr/bin/env node
import {readFileSync,writeFileSync} from "node:fs";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(fileURLToPath(new URL("..",import.meta.url)));
const source=JSON.parse(readFileSync(resolve(root,"catalog/products.json"),"utf8"));
const errors=[],seen=new Map(),names=new Set();
function validEAN(raw){
  if(typeof raw!=="string"||!(/^\d{8}$|^\d{12,14}$/).test(raw))return false;
  let sum=0,w=3;
  for(let i=raw.length-2;i>=0;i--){sum+=Number(raw[i])*w;w=w===3?1:3;}
  return (10-sum%10)%10===Number(raw.at(-1));
}
if(source.schema_version!==1||!Array.isArray(source.products))errors.push("Invalid schema.");
for(const [i,p] of (source.products||[]).entries()){
  const path="products["+i+"]";
  if(!validEAN(p.ean))errors.push(path+": invalid GTIN "+p.ean);
  if(seen.has(p.ean))errors.push(path+": duplicate EAN "+p.ean+" and "+seen.get(p.ean));
  seen.set(p.ean,i);
  if(!p.brand||!p.name||!p.source||!/^https:\/\//.test(p.source_url||""))errors.push(path+": missing source/product fields.");
  if(!Number.isInteger(p.quantity_g)||p.quantity_g<=0)errors.push(path+": invalid quantity.");
  if(!["Virginia","Dark Blend","Unbekannt"].includes(p.base))errors.push(path+": invalid tobacco base.");
  const duplicate=String(p.brand).toLowerCase()+":"+String(p.name).toLowerCase()+":"+p.quantity_g;
  // Same product and weight may legitimately have several retailer-documented GTINs (revisions).
  names.add(duplicate);
}
if(errors.length){console.error(errors.join("\n"));process.exit(1);}
const text="/* Generated by scripts/build-catalog.mjs from catalog/products.json. Do not edit manually. */\nwindow.TabakCatalog = "+
  JSON.stringify({schema_version:source.schema_version,updated_at:source.updated_at,products:source.products})+";\n";
const target=resolve(root,"catalog.js");
if(process.argv.includes("--check")){
  if(readFileSync(target,"utf8")!==text){console.error("catalog.js is out of sync; run node scripts/build-catalog.mjs");process.exit(1);}
  console.log("Catalog valid:",source.products.length,"EAN/GTIN records,",new Set(source.products.map(p=>p.brand)).size,"brands/lines.");
}else{
  writeFileSync(target,text);
  console.log("Generated catalog.js with",source.products.length,"products.");
}
